-- 2. DISPLAY FIRST NAME IN ASCENDING ORDER

SELECT FIRST_NAME AS Employee_Name
FROM EMP
ORDER BY FIRST_NAME ASC;


-- 3. DISPLAY FIRST NAME IN DESCENDING ORDER

SELECT FIRST_NAME AS Employee_Name
FROM EMP
ORDER BY FIRST_NAME DESC;


-- 4. DISPLAY HIRE DATE IN ASCENDING ORDER

SELECT HIRE_DATE
FROM EMP
ORDER BY HIRE_DATE ASC;


-- 5. EMPLOYEES WHOSE FIRST NAME STARTS WITH J OR M
-- SORT BY LAST NAME

SELECT *
FROM EMP
WHERE FIRST_NAME LIKE 'J%'
OR FIRST_NAME LIKE 'M%'
ORDER BY LAST_NAME ASC;


-- 6. MAXIMUM, MINIMUM, AVERAGE AND SUM OF SALARY

SELECT
MAX(SAL) AS Max,
MIN(SAL) AS Min,
AVG(SAL) AS Avg,
SUM(SAL) AS `Sum`
FROM EMP;


-- 7. SALARY STATISTICS FOR EACH JOB TYPE

SELECT JOB_ID,
MAX(SAL) AS Max,
MIN(SAL) AS Min,
AVG(SAL) AS Avg,
SUM(SAL) AS `Sum`
FROM EMP
GROUP BY JOB_ID;


-- 8. DISPLAY NUMBER OF EMPLOYEES UNDER EACH JOB

SELECT JOB_ID, COUNT(*) AS Number_of_Employees
FROM EMP
GROUP BY JOB_ID;


-- 9. DISPLAY NUMBER OF MANAGERS

SELECT COUNT(*) AS Number_of_Managers
FROM EMP
WHERE JOB_ID LIKE '%MGR%';


-- 10. DIFFERENCE BETWEEN HIGHEST AND LOWEST SALARY

SELECT MAX(SAL) - MIN(SAL) AS Salary_Difference
FROM EMP;


-- 11. MAXIMUM AND AVERAGE SALARY OF ENGINEERS
-- IT_PROG REPRESENTS PROGRAMMERS IN THIS DATASET

SELECT
MAX(SAL) AS Maximum_Salary,
AVG(SAL) AS Average_Salary
FROM EMP
WHERE JOB_ID = 'IT_PROG';


-- 12. FIRST AND LAST EMPLOYEE NAME ALPHABETICALLY

SELECT
MIN(FIRST_NAME) AS First_Employee,
MAX(FIRST_NAME) AS Last_Employee
FROM EMP;


-- 13. FIRST AND LAST HIRE DATE

SELECT
MIN(HIRE_DATE) AS `First Hire_Date`,
MAX(HIRE_DATE) AS `Last Hire_Date`
FROM EMP;


-- 14. MAXIMUM AND AVERAGE SALARY OF CLERKS

SELECT
MAX(SAL) AS Maximum_Salary,
AVG(SAL) AS Average_Salary
FROM EMP
WHERE JOB_ID LIKE '%CLERK%';


-- 15. DEPARTMENT NUMBER AND LOWEST SALARY

SELECT
DEPT_ID,
MIN(SAL) AS Minimum_Salary
FROM EMP
GROUP BY DEPT_ID;


-- 16. DEPARTMENTS HAVING MINIMUM SALARY GREATER THAN 3000

SELECT
DEPT_ID,
MIN(SAL) AS Minimum_Salary
FROM EMP
GROUP BY DEPT_ID
HAVING MIN(SAL) > 3000
ORDER BY Minimum_Salary DESC;


-- 17. DISPLAY EMPLOYEE SALARY INFORMATION IN SENTENCE FORMAT

SELECT CONCAT(
FIRST_NAME,
' whose designation is ',
JOB_ID,
' gets ',
SAL,
' but wants to earn ',
SAL * 3
) AS Employee_Details
FROM EMP;


-- 18. DISPLAY ALL EMPLOYEE DETAILS IN COMMA SEPARATED FORMAT

SELECT CONCAT(
EMP_ID, ', ',
FIRST_NAME, ', ',
LAST_NAME, ', ',
DATE_FORMAT(HIRE_DATE, '%d-%b-%y'), ', ',
JOB_ID, ', ',
SAL, ', ',
DEPT_ID
) AS Employee_Details
FROM EMP;


